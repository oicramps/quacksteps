// --- the runner, with fake git and a fake agent -------------------------------------

const config = { worktreeRoot: '/virtual/worktrees', scanRoots: [], repoPaths: {}, retentionDays: 7, maxWorktrees: 20 } as unknown as Config;

function fakeAgent(replies: (string | ((opts: AskOpts) => Promise<string>))[]) {
  const asks: AskOpts[] = [];
  const closed: string[] = [];
  const adapter: Adapter = {
    id: 'cursor',
    label: 'Cursor',
    isAvailable: async () => ({ id: 'cursor', label: 'Cursor', state: 'ready', models: [], fixSteps: [] }),
    async *ask(opts): AsyncIterable<AdapterEvent> {
      asks.push(opts);
      const r = replies.shift() ?? '';
      const text = typeof r === 'string' ? r : await r(opts);
      yield { type: 'session', sessionId: 's1' };
      yield { type: 'text', delta: text };
    },
    closeSession: (id) => closed.push(id),
  };
  return { adapter, asks, closed };
}

function setup(files: NumstatEntry[], replies: Parameters<typeof fakeAgent>[0], over: Partial<LabelOps> = {}) {
  const db = openDb(':memory:');
  const agent = fakeAgent(replies);
  const reads: string[] = [];
  const ops: LabelOps = {
    findClone: async () => ({ clone: '/clones/web', blockedRoots: [] }),
    context: async () => ({ baseSha: 'c'.repeat(40), title: 'Add login', body: 'Body' }),
    numstat: async () => files,
    diff: async () => files.map((f) => `diff --git a/${f.path} b/${f.path}\n+x\n`).join(''),
    readStart: async () => null,
    read: async (_clone, _dir, sha) => {
      reads.push(sha);
      return async () => {
        reads.push('released');
      };
    },
    ...over,
  };
  const statuses: string[] = [];
  const views: LabelsView[] = [];
  const runner = new LabelRunner({
    db,
    config: () => config,
    ops,
    adapters: { cursor: agent.adapter, 'claude-code': agent.adapter } as Record<AgentId, Adapter>,
    onStatus: (_pr, s) => statuses.push(s),
  });
  runner.subscribe((_pr, v) => views.push(v));
  return { db, runner, statuses, views, reads, ...agent };
}

const reply = (labels: [string, string, string][]) => JSON.stringify({ files: labels.map(([path, risk, reason]) => ({ path, risk, reason })) });

test('a run labels rule files itself, sends the rest to the agent, ranks and caches', async () => {
  const t = setup([entry('yarn.lock', 4000, 3000), entry('src/auth.ts', 40, 2), entry('src/util.ts', 3)], [
    reply([
      ['src/auth.ts', 'high', 'Changes token checks'],
      ['src/util.ts', 'low', 'Helper rename'],
    ]),
  ]);
  const first = t.runner.run(PR, A, { agent: 'cursor', model: 'fast' });
  assert.equal(first.status, 'running');
  await t.runner.idle();

  const done = t.views.at(-1)!;
  assert.equal(done.status, 'ready');
  assert.deepEqual(done.files.map((f) => [f.path, f.risk, f.source, f.rank]), [
    ['src/auth.ts', 'high', 'agent', 0],
    ['yarn.lock', 'low', 'rule', 1],
    ['src/util.ts', 'low', 'agent', 2],
  ]);
  assert.deepEqual(t.statuses, ['running', 'ready']);
  assert.deepEqual(t.reads, [A, 'released'], 'reads the review worktree at the head, then lets go');
  assert.equal(t.asks[0].model, 'fast');
  assert.doesNotMatch(t.asks[0].prompt, /Files to label:[^]*yarn\.lock[^]*Diff:/, 'rule files never reach the agent as files to label');
  assert.deepEqual(t.closed, ['s1'], 'the agent session is closed after the job');

  // Cached: the same commit and settings answer at once, without the agent.
  const again = t.runner.run(PR, A, { agent: 'cursor', model: 'fast' });
  assert.equal(again.status, 'ready');
  assert.equal(t.asks.length, 1);
  assert.equal(t.runner.get(PR, A)!.files.length, 3);
});

