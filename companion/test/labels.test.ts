test('files the agent skipped become unlabeled; large PRs send only the 60 largest files', async () => {
  const many = Array.from({ length: 160 }, (_, i) => entry(`f${String(i).padStart(3, '0')}.ts`, i + 1));
  const t = setup(many, [reply([['f159.ts', 'high', 'Biggest']])]);
  t.runner.run(PR, A);
  await t.runner.idle();
  const done = t.views.at(-1)!;
  const prompt = t.asks[0].prompt;
  assert.match(prompt, /- f159\.ts/);
  assert.match(prompt, /- f100\.ts/);
  assert.doesNotMatch(prompt, /^- f099\.ts$/m, 'only the 60 largest are sent');
  const byPath = new Map(done.files.map((f) => [f.path, f]));
  assert.equal(byPath.get('f159.ts')!.risk, 'high');
  assert.equal(byPath.get('f120.ts')!.reason, 'Not labeled by the agent. Review by hand');
  assert.equal(byPath.get('f000.ts')!.reason, 'Too big to label. Review by hand');
  assert.equal(done.files.length, 160);
});

test('at most two jobs run at once; the third is queued', async () => {
  const gates: (() => void)[] = [];
  const slow = () => new Promise<string>((r) => gates.push(() => r(reply([['a.ts', 'low', 'ok']]))));
  const t = setup([entry('a.ts')], [slow, slow, slow]);
  const prs = [1, 2, 3].map((number) => ({ ...PR, number }));
  const views = prs.map((pr) => t.runner.run(pr, A));
  assert.equal(views[2].queued, true);
  await new Promise((r) => setTimeout(r, 10));
  assert.equal(gates.length, 2, 'two agents running');
  gates.shift()!();
  await new Promise((r) => setTimeout(r, 10));
  assert.equal(gates.length, 2, 'the third started when one finished');
  assert.equal(t.runner.get(prs[2])!.queued, undefined);
  for (const g of gates.splice(0)) g();
  await t.runner.idle();
  assert.ok(prs.every((pr) => t.runner.get(pr)!.status === 'ready'));
});

test('a new commit cancels the old job and keeps the old labels visible meanwhile', async () => {
  let release!: () => void;
  const t = setup([entry('a.ts')], [reply([['a.ts', 'low', 'v1']]), () => new Promise<string>((r) => (release = () => r(reply([['a.ts', 'high', 'v2']]))))]);
  t.runner.run(PR, A);
  await t.runner.idle();
  const running = t.runner.run(PR, B);
  assert.equal(running.status, 'running');
  assert.equal(running.previousHeadSha, A);
  assert.equal(running.files[0].reason, 'v1', 'old labels shown, dimmed, until the new run finishes');
  await new Promise((r) => setTimeout(r, 10));
  release();
  await t.runner.idle();
  assert.equal(t.runner.get(PR)!.headSha, B);
  assert.equal(t.runner.get(PR)!.files[0].reason, 'v2');
  assert.equal(t.runner.get(PR, A)!.files[0].reason, 'v1', 'labels for the old commit stay cached');
});

test('cancelling a job publishes nothing more and releases the worktree', async () => {
  const t = setup([entry('a.ts')], [(opts) => new Promise<string>((_, reject) => opts.signal.addEventListener('abort', () => reject(new Error('aborted'))))]);
  t.runner.run(PR, A);
  await new Promise((r) => setTimeout(r, 10));
  const published = t.views.length;
  t.runner.cancel(PR);
  await t.runner.idle();
  assert.equal(t.views.length, published);
  assert.deepEqual(t.reads, [A, 'released']);
  assert.equal(t.runner.get(PR), undefined);
});

