test('parseNumstat reads plain entries, renames and binaries from -z output', () => {
  const out = ['3\t1\tsrc/app.ts', '0\t0\t', 'old/name.ts', 'new/name.ts', '-\t-\tlogo.png', ''].join('\0');
  assert.deepEqual(parseNumstat(out), [
    { path: 'src/app.ts', added: 3, deleted: 1, binary: false },
    { path: 'new/name.ts', oldPath: 'old/name.ts', added: 0, deleted: 0, binary: false },
    { path: 'logo.png', added: 0, deleted: 0, binary: true },
  ]);
});

test('rules label lockfiles, snapshots, vendored, built and generated files and pure renames', () => {
  const cases: [NumstatEntry, string | null, string | null][] = [
    [entry('yarn.lock'), null, 'Lockfile'],
    [entry('ios/Podfile.lock'), null, 'Lockfile'],
    [entry('src/__snapshots__/a.test.ts.snap'), null, 'Snapshot'],
    [entry('vendor/lib/x.go'), null, 'Vendored code'],
    [entry('packages/ui/dist/index.js'), null, 'Build output'],
    [entry('api/user.pb.go'), null, 'Generated file'],
    [entry('schema.gen.ts'), null, 'Generated file'],
    [entry('src/client.ts'), '// @generated by codegen\n', 'Generated file'],
    [entry('b.ts', 0, 0, { oldPath: 'a.ts' }), null, 'Rename only'],
    [entry('b.ts', 2, 1, { oldPath: 'a.ts' }), null, null],
    [entry('src/vendor.ts'), null, null],
    [entry('src/auth.ts'), 'export function login() {}', null],
  ];
  for (const [e, head, want] of cases) assert.equal(ruleReason(e, head), want, e.path);
});

test('splitDiff keys chunks by the new path, renames included', () => {
  const diff = 'diff --git a/x.ts b/x.ts\n+one\ndiff --git a/old.ts b/new.ts\n+two\n';
  const chunks = splitDiff(diff, [entry('x.ts'), entry('new.ts', 1, 0, { oldPath: 'old.ts' })]);
  assert.equal(chunks.get('x.ts'), 'diff --git a/x.ts b/x.ts\n+one\n');
  assert.equal(chunks.get('new.ts'), 'diff --git a/old.ts b/new.ts\n+two\n');
});

test('the prompt keeps the diff within budget, largest first, and lists what it left out', () => {
  const big = entry('big.ts', 900);
  const small = entry('small.ts', 5);
  const huge = entry('huge.ts', 2000);
  const chunks = new Map([
    ['huge.ts', `diff --git a/huge.ts b/huge.ts\n${'+'.repeat(DIFF_BUDGET + 10)}\n`],
    ['big.ts', 'diff --git a/big.ts b/big.ts\n+big\n'],
    ['small.ts', 'diff --git a/small.ts b/small.ts\n+small\n'],
  ]);
  const prompt = buildLabelPrompt({ pr: PR, title: 'T', body: '', all: [small, big, huge], toLabel: [small, big, huge], chunks });
  assert.match(prompt, /\[diff of huge\.ts truncated\]/);
  assert.match(prompt, /open them if needed:\n- big\.ts\n- small\.ts/);
  const diffPart = prompt.slice(prompt.indexOf('Diff:'));
  assert.ok(diffPart.length < DIFF_BUDGET + 200);
});

test('parseLabels is strict about shape, drops unknown paths and trims reasons', () => {
  const allowed = new Set(['a.ts', 'b.ts']);
  const reply = '```json\n{"files":[{"path":"a.ts","risk":"high","reason":"Changes the\\nauth check"},{"path":"zzz.ts","risk":"low","reason":"x"},{"path":"b.ts","risk":"low","reason":"' + 'r'.repeat(200) + '"}]}\n```';
  const got = parseLabels(reply, allowed);
  assert.deepEqual(got.get('a.ts'), { risk: 'high', reason: 'Changes the auth check' });
  assert.equal(got.has('zzz.ts'), false);
  assert.equal(got.get('b.ts')!.reason.length, 90);
  assert.throws(() => parseLabels('I think a.ts is risky', allowed), /no JSON/);
  assert.throws(() => parseLabels('{"files":[{"path":"a.ts","risk":"critical","reason":"x"}]}', allowed), /unknown risk/);
  assert.throws(() => parseLabels('{"files":{}}', allowed), /not an array/);
});

